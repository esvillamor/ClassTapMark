  function buildLearnerRows(bundle, classId, period) {
    const periodObj = getPeriodObj(classId, period);
    const dateOfMeasurement = isoDateOrEmpty(
      pick(periodObj, ['dateOfMeasurement', 'DateOfMeasurement']) ||
      pick(bundle.header, ['dateOfMeasurement', 'DateOfMeasurement'])
    );

    const profById = new Map();
    for (const p of bundle.profiles) {
      if (p && p.studentId != null) profById.set(String(p.studentId), p);
    }

    const rows = [];
    // Separate numbering per sex (Male & Female)
    let maleNo = 0;
    let femaleNo = 0;
    let otherNo = 0;

    for (const st of bundle.roster) {
      if (!st || !st.id) continue;
      const sid = String(st.id);
      const prof = profById.get(sid) || {};
      const rec = getRecord(periodObj, sid) || {};

      const lrn = pick(rec, ['lrn', 'LRN']) || pick(prof, ['lrn', 'LRN', 'LRN']) || '';
      const birth = isoDateOrEmpty(pick(rec, ['birthdate', 'Birthdate']) || pick(prof, ['birthdate', 'Birthdate']));
      const wtRaw = pick(rec, ['weightKg', 'weight', 'wt', 'WeightKg', 'Weight']);
      const htRaw = pick(rec, ['heightM', 'height', 'ht', 'HeightM', 'Height']);

      const wt = (wtRaw === '' || wtRaw == null) ? null : Number(wtRaw);
      const ht = (htRaw === '' || htRaw == null) ? null : normalizeHeightMeters(htRaw);
      const ht2 = (Number.isFinite(ht) && ht > 0) ? (ht * ht) : null;
      const bmi = (Number.isFinite(wt) && Number.isFinite(ht2) && ht2 > 0) ? (wt / ht2) : null;
      const sexRaw = toStr(st.sex || prof.sex).trim();
      const sexNorm = normalizeSexMF(st.sex || prof.sex);
      const ageMonths = computeAgeMonths(birth, dateOfMeasurement);

      const bmiCatRaw = pick(rec, ['bmiCategory', 'BMICategory', 'bmiCat', 'BMIcat']);
      const hfaRaw = pick(rec, ['heightForAge', 'HeightforAge', 'hfa', 'HFA', 'hfaCategory']);
      const remarks = pick(rec, ['remarks', 'Remarks', 'note', 'Note']) || '';

      const bmiCatComputed = (sexRaw && ageMonths != null && bmi != null) ? (sf8GetBmiCategory(sexRaw, ageMonths, bmi) || '') : '';

      const bmiCat = bmiCatComputed ||
        normalizeCat(bmiCatRaw, NS_CATS) ||
        bmiCatLabel(bmiCatRaw);

      const hfaComputed = (sexRaw && ageMonths != null && ht != null) ? (sf8GetHfaCategory(sexRaw, ageMonths, ht) || '') : '';

      const hfa = hfaComputed ||
        normalizeCat(hfaRaw, HFA_CATS) ||
        hfaLabel(hfaRaw);
      rows.push({
        no: (sexNorm === 'F' ? ++femaleNo : (sexNorm === 'M' ? ++maleNo : ++otherNo)),
        lrn: toStr(lrn),
        name: toStr(st.name || prof.learnerName || ''),
        sex: sexNorm,
        birthdate: birth,
        age: (computeAgeYears(birth, dateOfMeasurement) ?? ''),
        wt: (wt == null ? '' : fmt(wt, 2)),
        ht: (ht == null ? '' : fmt(ht, 2)),
        ht2: (ht2 == null ? '' : fmt(ht2, 3)),
        bmi: (bmi == null ? '' : fmt(bmi, 2)),
        bmiCat,
        hfa,
        remarks: toStr(remarks)
      });
    }

    // --- FIX: Sort within sex by learner name (A→Z), case-insensitive, then re-number per sex
	const sexOrder = (s) => (s === 'M' ? 0 : s === 'F' ? 1 : 2);

	// Name normalization for consistent ordering (trim, collapse spaces)
	const normName = (s) => toStr(s).trim().replace(/\s+/g, ' ');

	// Prefer Intl.Collator if available (better A→Z, ignores case/punct nicely)
	const collator =
	  (typeof Intl !== 'undefined' && Intl.Collator)
		? new Intl.Collator('en', { sensitivity: 'base', numeric: true, ignorePunctuation: true })
		: null;

	// stable sort: preserve original order when names match
	rows.forEach((r, i) => (r.__i = i));

	rows.sort((a, b) => {
	  // 1) Male first, then Female, then others
	  let d = sexOrder(a.sex) - sexOrder(b.sex);
	  if (d) return d;

	  // 2) Alphabetical by name within same sex
	  const an = normName(a.name);
	  const bn = normName(b.name);

	  d = collator ? collator.compare(an, bn) : an.toUpperCase().localeCompare(bn.toUpperCase());
	  if (d) return d;

	  // 3) Stable fallback
	  return a.__i - b.__i;
	});

	rows.forEach(r => { delete r.__i; });

	// Re-number after sorting so Male and Female each start at 1
	maleNo = 0; femaleNo = 0; otherNo = 0;
	for (const r of rows) {
	  if (r.sex === 'M') r.no = ++maleNo;
	  else if (r.sex === 'F') r.no = ++femaleNo;
	  else r.no = ++otherNo;
	}
	
	return { rows, dateOfMeasurement };
  }

  function buildSummary(rows) {
    function initRow(cats) {
      const o = {};
      cats.forEach(k => o[k] = 0);
      // TOTAL in the PDF summary table should reflect the total number of learners (by sex),
      // while category counts should reflect ONLY learners with complete encoded data.
      o.TOTAL = 0;
      return o;
    }

    const ns = { Male: initRow(NS_CATS), Female: initRow(NS_CATS), Total: initRow(NS_CATS) };
    const hfa = { Male: initRow(HFA_CATS), Female: initRow(HFA_CATS), Total: initRow(HFA_CATS) };

    const totals = { Male: 0, Female: 0, Total: 0 };

    for (const r of rows) {
      const sex = (toStr(r.sex).toUpperCase() === 'F') ? 'Female' : 'Male';
      totals[sex]++; totals.Total++;

      // Nutritional Status categories: count ONLY if BMI category is actually computed/encoded
      const c1 = normalizeCat(r.bmiCat, NS_CATS);
      if (c1) { ns[sex][c1]++; ns.Total[c1]++; }

      // Height-for-Age categories: count ONLY if HFA is actually computed/encoded
      const c2 = normalizeCat(r.hfa, HFA_CATS);
      if (c2) { hfa[sex][c2]++; hfa.Total[c2]++; }
    }

    // Set TOTALs to roster totals (not the sum of categories)
    ns.Male.TOTAL = totals.Male;
    ns.Female.TOTAL = totals.Female;
    ns.Total.TOTAL = totals.Total;

    hfa.Male.TOTAL = totals.Male;
    hfa.Female.TOTAL = totals.Female;
    hfa.Total.TOTAL = totals.Total;

    return { ns, hfa };
  }

