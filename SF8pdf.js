  function bmiCatLabel(v) {
    // IMPORTANT: do not coerce empty string to 0 (Number('') === 0) because it falsely maps to 'Severely Wasted'
    const s0 = toStr(v).trim();
    if (!s0) return '';
    const n = Number(s0);
    if (!Number.isFinite(n)) return '';
    const map0 = ['Severely Wasted', 'Wasted', 'Normal', 'Overweight', 'Obese'];
    const map1 = ['', 'Severely Wasted', 'Wasted', 'Normal', 'Overweight', 'Obese'];
    if (n >= 0 && n <= 4) return map0[Math.round(n)] || '';
    if (n >= 1 && n <= 5) return map1[Math.round(n)] || '';
    return '';
  }

