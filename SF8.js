function sf8GetBmiCategory(sex, ageMonths, bmi) {
  if (!sex || !isFinite(ageMonths) || !isFinite(bmi)) return null;
  const row = SF8_LOOKUP.bmiRow(sex, ageMonths);
  if (!row) return null;
  const sw=row[1], wF=row[2], wT=row[3], nF=row[4], nT=row[5], owF=row[6], owT=row[7], ob=row[8];
  if (bmi <= sw) return 'Severely Wasted';
  if (bmi >= ob) return 'Obese';
  if (bmi >= wF && bmi <= wT) return 'Wasted';
  if (bmi >= owF && bmi <= owT) return 'Overweight';
  if (bmi >= nF && bmi <= nT) return 'Normal';
  if (bmi < nF) return (bmi <= wT ? 'Wasted' : 'Normal');
  if (bmi > nT) return (bmi >= owF ? 'Overweight' : 'Normal');
  return 'Normal';
}

function sf8GetHfaCategory(sex, ageMonths, heightM) {
  if (!sex || !isFinite(ageMonths) || !isFinite(heightM)) return null;
  const row = SF8_LOOKUP.hfaRow(sex, ageMonths);
  if (!row) return null;
  const hcm = heightM * 100;
  const ss=row[1], sF=row[2], sT=row[3], nF=row[4], nT=row[5], tall=row[6];
  if (hcm <= ss) return 'Severely Stunted';
  if (hcm >= tall) return 'Tall';
  if (hcm >= sF && hcm <= sT) return 'Stunted';
  if (hcm >= nF && hcm <= nT) return 'Normal';
  if (hcm < nF) return (hcm <= sT ? 'Stunted' : 'Normal');
  if (hcm > nT) return (hcm >= tall ? 'Tall' : 'Normal');
  return 'Normal';
}

