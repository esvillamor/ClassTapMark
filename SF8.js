function buildLearnerSelect() {
  const sel = $('sf8LearnerSelect');
  if (!sel) return;

  sel.innerHTML = '<option value="">Select learner…</option>';

  const learners = sf8State.roster || [];

  // Build sortable items but KEEP original roster index for opt.value
  const items = learners.map((st, i) => {
    const profSex = getProfileByStudentId(st.id)?.sex;

    const sexRaw = String(profSex || st.sex || '').trim().toLowerCase();
    let sexNorm = '';
    if (sexRaw === 'm' || sexRaw.startsWith('male')) sexNorm = 'Male';
    else if (sexRaw === 'f' || sexRaw.startsWith('female')) sexNorm = 'Female';

    // Use roster name, fallback to profile learnerName if needed
    const nameRaw = String(st.name || getProfileByStudentId(st.id)?.learnerName || '').trim();
    // Sort key: strip any "(Male)/(Female)" suffix, compare case-insensitive
    const nameKey = sf8StripSexSuffix(nameRaw).toLowerCase();

    return { st, i, profSex, sexNorm, nameRaw, nameKey };
  });

  // Group by sex (to match SF8 layout expectations)
  const male = [];
  const female = [];
  const other = [];

  for (const it of items) {
    if (it.sexNorm === 'Male') male.push(it);
    else if (it.sexNorm === 'Female') female.push(it);
    else other.push(it);
  }

  const cmp = (a, b) =>
    a.nameKey.localeCompare(b.nameKey, undefined, { sensitivity: 'base' }) ||
    (a.i - b.i); // stable tie-breaker

  male.sort(cmp);
  female.sort(cmp);
  other.sort(cmp);

  const ordered = [...male, ...female, ...other];

  // Numbering per sex, now consistent because groups are ordered
  let maleN = 0, femaleN = 0, otherN = 0;

  for (const it of ordered) {
    const opt = document.createElement('option');

    // IMPORTANT: keep original roster index so existing code still works
    opt.value = String(it.i);

    let n = '';
    if (it.sexNorm === 'Male') n = String(++maleN);
    else if (it.sexNorm === 'Female') n = String(++femaleN);
    else n = String(++otherN);

    const displayName = sf8NameWithSex(it.nameRaw, it.sexNorm || it.profSex || it.st.sex);
    opt.textContent = `${n} - ${displayName}`;

    sel.appendChild(opt);
  }

  // Preserve selected learner (by roster index)
  if (sf8State.idx >= 0 && sf8State.idx < learners.length) {
    sel.value = String(sf8State.idx);
  }
}

